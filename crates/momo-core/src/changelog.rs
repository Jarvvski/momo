//! The `CHANGELOG.md` document: parsing the Unreleased Changes out of it and
//! recording new ones into it.
//!
//! Pure text: reading and writing the file is the CLI's job. Only the Unreleased
//! section is understood; released sections are carried through verbatim.

use crate::change::{Change, Kind};

/// The title and intro written above the first `##` heading of a new changelog.
const INTRO: &str = "\
# Changelog

All notable changes to this package are documented here, generated by
[momo](https://github.com/Jarvvski/momo).";

/// The heading momo writes for the Unreleased section.
const UNRELEASED_HEADING: &str = "## [Unreleased]";

/// A parsed `CHANGELOG.md`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Changelog {
    /// The document before the first `##` heading: title and intro.
    preamble: Vec<String>,
    /// The Unreleased Changes, when the document has an Unreleased section.
    unreleased: Option<Vec<Change>>,
    /// Every line from the first released `##` heading onwards, verbatim.
    released: Vec<String>,
}

impl Changelog {
    /// A new changelog holding only the standard intro and an empty Unreleased
    /// section.
    pub fn empty() -> Self {
        Self {
            preamble: INTRO.lines().map(str::to_owned).collect(),
            unreleased: Some(Vec::new()),
            released: Vec::new(),
        }
    }

    /// Parse `text` into a changelog.
    pub fn parse(text: &str) -> Self {
        let lines: Vec<&str> = text.lines().collect();

        let Some(start) = lines.iter().position(|line| is_unreleased(line)) else {
            let split = lines
                .iter()
                .position(|line| is_section(line))
                .unwrap_or(lines.len());
            return Self {
                preamble: owned(&lines[..split]),
                unreleased: None,
                released: owned(&lines[split..]),
            };
        };

        let body_start = start + 1;
        let body_end = lines[body_start..]
            .iter()
            .position(|line| is_section(line))
            .map(|offset| body_start + offset)
            .unwrap_or(lines.len());

        Self {
            preamble: owned(&lines[..start]),
            unreleased: Some(entries(&lines[body_start..body_end])),
            released: owned(&lines[body_end..]),
        }
    }

    /// Record one Change under Unreleased.
    pub fn record(&mut self, change: Change) {
        self.unreleased.get_or_insert_with(Vec::new).push(change);
    }

    /// The Unreleased Changes.
    pub fn unreleased(&self) -> &[Change] {
        self.unreleased.as_deref().unwrap_or(&[])
    }

    /// Consume the changelog, returning its Unreleased Changes.
    pub fn into_unreleased(self) -> Vec<Change> {
        self.unreleased.unwrap_or_default()
    }

    /// Render the changelog back to Markdown.
    pub fn render(&self) -> String {
        let mut lines = self.preamble.clone();

        if let Some(changes) = &self.unreleased {
            blank(&mut lines);
            lines.push(UNRELEASED_HEADING.to_owned());
            for kind in Kind::ALL {
                let matching: Vec<&Change> = changes
                    .iter()
                    .filter(|change| change.kind == kind)
                    .collect();
                if matching.is_empty() {
                    continue;
                }
                blank(&mut lines);
                lines.push(format!("### {}", kind.heading()));
                blank(&mut lines);
                lines.extend(matching.iter().map(|change| format!("- {}", change.text)));
            }
        }

        if !self.released.is_empty() {
            blank(&mut lines);
            lines.extend(self.released.iter().cloned());
        }

        let mut rendered = lines.join("\n");
        rendered.push('\n');
        rendered
    }
}

/// Whether `line` is a level-2 (`## `) heading.
fn is_section(line: &str) -> bool {
    line.starts_with("## ")
}

/// Whether `line` heads the Unreleased section, in either accepted spelling.
fn is_unreleased(line: &str) -> bool {
    matches!(
        line.strip_prefix("## ").map(str::trim),
        Some("[Unreleased]") | Some("Unreleased")
    )
}

/// Own a slice of borrowed lines.
fn owned(lines: &[&str]) -> Vec<String> {
    lines.iter().map(|line| (*line).to_owned()).collect()
}

/// Parse the entries of an Unreleased body, grouped by their `###` heading.
fn entries(body: &[&str]) -> Vec<Change> {
    let mut changes = Vec::new();
    let mut kind = None;
    for line in body {
        if let Some(heading) = line.strip_prefix("### ") {
            kind = Kind::from_heading(heading);
        } else if let Some(text) = line.strip_prefix("- ")
            && let Some(kind) = kind
        {
            changes.push(Change::new(kind, text.trim()));
        }
    }
    changes
}

/// Push a blank line unless the buffer is empty or already ends with one.
fn blank(lines: &mut Vec<String>) {
    if lines.last().is_some_and(|line| !line.is_empty()) {
        lines.push(String::new());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn change(kind: Kind, text: &str) -> Change {
        Change::new(kind, text)
    }

    #[test]
    fn recording_into_a_new_changelog_writes_the_intro_and_a_section() {
        let mut changelog = Changelog::empty();
        changelog.record(change(Kind::Add, "Add a thing"));

        assert_eq!(
            changelog.render(),
            "\
# Changelog

All notable changes to this package are documented here, generated by
[momo](https://github.com/Jarvvski/momo).

## [Unreleased]

### Added

- Add a thing
"
        );
    }

    #[test]
    fn sections_render_highest_kind_first() {
        let mut changelog = Changelog::empty();
        changelog.record(change(Kind::Fix, "a fix"));
        changelog.record(change(Kind::Add, "an add"));
        changelog.record(change(Kind::Break, "a break"));

        let rendered = changelog.render();
        let breaking = rendered.find("### Breaking").expect("breaking section");
        let added = rendered.find("### Added").expect("added section");
        let fixed = rendered.find("### Fixed").expect("fixed section");
        assert!(breaking < added && added < fixed, "{rendered}");
    }

    #[test]
    fn entries_within_a_kind_keep_their_order() {
        let mut changelog = Changelog::empty();
        changelog.record(change(Kind::Add, "first"));
        changelog.record(change(Kind::Add, "second"));

        let rendered = changelog.render();
        let first = rendered.find("- first").expect("first entry");
        let second = rendered.find("- second").expect("second entry");
        assert!(first < second, "{rendered}");
    }

    #[test]
    fn parse_recovers_the_unreleased_changes() {
        let text = "\
# Changelog

## [Unreleased]

### Breaking

- a break

### Fixed

- a fix

## [1.0.0] - 2026-01-01

### Added

- released thing
";
        let changelog = Changelog::parse(text);
        assert_eq!(
            changelog.unreleased(),
            &[change(Kind::Break, "a break"), change(Kind::Fix, "a fix")]
        );
    }

    #[test]
    fn recording_preserves_released_sections_and_inserts_unreleased_first() {
        let text = "\
# Changelog

## [1.0.0] - 2026-01-01

### Added

- released thing
";
        let mut changelog = Changelog::parse(text);
        assert!(changelog.unreleased().is_empty());
        changelog.record(change(Kind::Add, "new thing"));

        let rendered = changelog.render();
        let unreleased = rendered
            .find("## [Unreleased]")
            .expect("unreleased heading");
        let release = rendered
            .find("## [1.0.0] - 2026-01-01")
            .expect("release heading");
        assert!(unreleased < release, "{rendered}");
        assert!(rendered.contains("- new thing"), "{rendered}");
        assert!(rendered.contains("- released thing"), "{rendered}");
    }

    #[test]
    fn parse_accepts_both_unreleased_spellings() {
        for heading in ["## Unreleased", "## [Unreleased]"] {
            let text = format!("{heading}\n\n### Added\n\n- a thing\n");
            assert_eq!(
                Changelog::parse(&text).unreleased(),
                &[change(Kind::Add, "a thing")]
            );
        }
    }

    #[test]
    fn parsing_a_document_without_unreleased_reports_none() {
        let changelog = Changelog::parse("# Changelog\n");
        assert!(changelog.unreleased().is_empty());
        assert_eq!(changelog.into_unreleased(), Vec::new());
    }
}
