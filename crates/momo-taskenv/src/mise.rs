//! The mise adapter: writes self-contained `momo:*` file tasks.
//!
//! Each wrapper lives at `mise-tasks/momo/<verb>` — the path below `mise-tasks`
//! becomes the task name, so `mise-tasks/momo/status` is the task `momo:status`.
//! The `#MISE tools={…}` header pins the momo CLI as a `github:` dependency, so
//! the pin travels inside the task and no `mise.toml` is ever edited. This is
//! Shape B from `docs/mise-task-distribution.md`.

use std::fs;
use std::path::{Path, PathBuf};

use momo_core::taskenv::{InstallMode, InstallPlan, TaskEnvError, TaskEnvironment, TaskWrapper};
use semver::Version;

/// The mise `github:` backend the wrappers pin.
const TOOL: &str = "github:Jarvvski/momo";

/// A mise project, rooted where its `mise.toml` or `.mise/` lives.
#[derive(Debug, Clone)]
pub struct MiseTaskEnvironment {
    root: PathBuf,
    tasks_dir: PathBuf,
}

impl MiseTaskEnvironment {
    /// Root a mise adapter at `root`.
    pub fn new(root: impl Into<PathBuf>) -> Self {
        let root = root.into();
        let tasks_dir = root.join("mise-tasks").join("momo");
        Self { root, tasks_dir }
    }

    /// The wrapper for `verb`, pinning `version`.
    fn wrapper(&self, verb: &str, version: &Version) -> TaskWrapper {
        TaskWrapper {
            path: self.tasks_dir.join(verb),
            contents: format!(
                "#!/usr/bin/env bash\n\
                 # generated by momo {version} - refresh with: momo install --update\n\
                 #MISE description=\"Run momo {verb}\"\n\
                 #MISE tools={{ \"{TOOL}\" = \"{version}\" }}\n\
                 momo {verb} \"$@\"\n"
            ),
        }
    }
}

impl TaskEnvironment for MiseTaskEnvironment {
    fn name(&self) -> &'static str {
        "mise"
    }

    fn root(&self) -> &Path {
        &self.root
    }

    fn tasks_dir(&self) -> &Path {
        &self.tasks_dir
    }

    fn plan(
        &self,
        version: &Version,
        verbs: &[&str],
        mode: InstallMode,
    ) -> Result<InstallPlan, TaskEnvError> {
        let mut plan = InstallPlan::default();
        for verb in verbs {
            let wrapper = self.wrapper(verb, version);
            match fs::read_to_string(&wrapper.path) {
                Ok(existing) if existing == wrapper.contents => plan.unchanged.push(wrapper.path),
                Ok(_) => match mode {
                    InstallMode::Update => plan.writes.push(wrapper),
                    InstallMode::Install => plan.stale.push(wrapper.path),
                },
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    plan.writes.push(wrapper);
                }
                Err(source) => {
                    return Err(TaskEnvError::Read {
                        path: wrapper.path,
                        source,
                    });
                }
            }
        }
        Ok(plan)
    }

    fn write(&self, wrappers: &[TaskWrapper]) -> Result<(), TaskEnvError> {
        if wrappers.is_empty() {
            return Ok(());
        }
        fs::create_dir_all(&self.tasks_dir).map_err(|source| TaskEnvError::Write {
            path: self.tasks_dir.clone(),
            source,
        })?;
        for wrapper in wrappers {
            fs::write(&wrapper.path, &wrapper.contents).map_err(|source| TaskEnvError::Write {
                path: wrapper.path.clone(),
                source,
            })?;
            set_executable(&wrapper.path)?;
        }
        Ok(())
    }

    fn uninstall(&self) -> Result<(), TaskEnvError> {
        match fs::remove_dir_all(&self.tasks_dir) {
            Ok(()) => Ok(()),
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(source) => Err(TaskEnvError::Remove {
                path: self.tasks_dir.clone(),
                source,
            }),
        }
    }
}

/// Mark a wrapper executable; mise lists only executable files as tasks on Unix.
fn set_executable(path: &Path) -> Result<(), TaskEnvError> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(path, fs::Permissions::from_mode(0o755)).map_err(|source| {
            TaskEnvError::Write {
                path: path.to_path_buf(),
                source,
            }
        })?;
    }
    #[cfg(not(unix))]
    let _ = path;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    use tempfile::TempDir;

    fn adapter(dir: &TempDir) -> MiseTaskEnvironment {
        MiseTaskEnvironment::new(dir.path())
    }

    #[test]
    fn plan_writes_one_wrapper_per_verb() {
        let dir = TempDir::new().unwrap();
        let plan = adapter(&dir)
            .plan(
                &Version::new(0, 1, 0),
                &["status", "release"],
                InstallMode::Install,
            )
            .unwrap();
        assert_eq!(plan.writes.len(), 2);
        assert!(
            plan.writes
                .iter()
                .any(|wrapper| wrapper.path.ends_with("mise-tasks/momo/status"))
        );
        assert!(plan.unchanged.is_empty());
        assert!(plan.stale.is_empty());
    }

    #[test]
    fn write_makes_executable_wrappers_that_pin_the_version() {
        let dir = TempDir::new().unwrap();
        let env = adapter(&dir);
        let plan = env
            .plan(&Version::new(0, 1, 0), &["status"], InstallMode::Install)
            .unwrap();
        env.write(&plan.writes).unwrap();

        let path = dir.path().join("mise-tasks/momo/status");
        let text = fs::read_to_string(&path).unwrap();
        assert!(text.starts_with("#!/usr/bin/env bash\n"), "{text}");
        assert!(text.contains("# generated by momo 0.1.0"), "{text}");
        assert!(
            text.contains("#MISE tools={ \"github:Jarvvski/momo\" = \"0.1.0\" }"),
            "{text}"
        );
        assert!(text.contains("momo status \"$@\""), "{text}");

        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = fs::metadata(&path).unwrap().permissions().mode();
            assert_ne!(mode & 0o111, 0, "wrapper is not executable");
        }
    }

    #[test]
    fn installing_twice_is_a_noop() {
        let dir = TempDir::new().unwrap();
        let env = adapter(&dir);
        let version = Version::new(0, 1, 0);
        let first = env
            .plan(&version, &["status"], InstallMode::Install)
            .unwrap();
        env.write(&first.writes).unwrap();

        let second = env
            .plan(&version, &["status"], InstallMode::Install)
            .unwrap();
        assert!(second.writes.is_empty());
        assert_eq!(second.unchanged.len(), 1);
        assert!(second.stale.is_empty());
        assert!(second.is_noop());
    }

    #[test]
    fn install_leaves_a_stale_wrapper_untouched() {
        let dir = TempDir::new().unwrap();
        let env = adapter(&dir);
        let first = env
            .plan(&Version::new(0, 1, 0), &["status"], InstallMode::Install)
            .unwrap();
        env.write(&first.writes).unwrap();

        let plan = env
            .plan(&Version::new(0, 2, 0), &["status"], InstallMode::Install)
            .unwrap();
        assert!(plan.writes.is_empty());
        assert_eq!(plan.stale.len(), 1);

        let text = fs::read_to_string(dir.path().join("mise-tasks/momo/status")).unwrap();
        assert!(text.contains("0.1.0"), "{text}");
    }

    #[test]
    fn update_refreshes_a_stale_wrapper() {
        let dir = TempDir::new().unwrap();
        let env = adapter(&dir);
        let first = env
            .plan(&Version::new(0, 1, 0), &["status"], InstallMode::Install)
            .unwrap();
        env.write(&first.writes).unwrap();

        let plan = env
            .plan(&Version::new(0, 2, 0), &["status"], InstallMode::Update)
            .unwrap();
        assert_eq!(plan.writes.len(), 1);
        env.write(&plan.writes).unwrap();

        let text = fs::read_to_string(dir.path().join("mise-tasks/momo/status")).unwrap();
        assert!(text.contains("0.2.0"), "{text}");
        assert!(!text.contains("0.1.0"), "{text}");
    }

    #[test]
    fn uninstall_removes_the_wrapper_directory() {
        let dir = TempDir::new().unwrap();
        let env = adapter(&dir);
        let plan = env
            .plan(&Version::new(0, 1, 0), &["status"], InstallMode::Install)
            .unwrap();
        env.write(&plan.writes).unwrap();

        env.uninstall().unwrap();
        assert!(!dir.path().join("mise-tasks/momo").exists());
    }

    #[test]
    fn uninstall_is_a_noop_when_nothing_was_installed() {
        let dir = TempDir::new().unwrap();
        adapter(&dir).uninstall().unwrap();
    }
}
