//! Integration tests for manifest sync: `release` writes the minted Version into
//! the Package's `Cargo.toml`, format-preserving, and warns about a stale
//! `Cargo.lock` rather than rewriting it.
//!
//! These drive the real binary. A project is created in a directory named `proj`
//! so the reported Package name is deterministic.

use std::fs;
use std::path::{Path, PathBuf};

use assert_cmd::Command;
use predicates::prelude::*;
use tempfile::TempDir;

/// The `MOMO_*` variables the CLI reads; every test clears them.
const MOMO_VARS: [&str; 7] = [
    "MOMO_RECORDING",
    "MOMO_CHANGELOG",
    "MOMO_CHANGES_DIR",
    "MOMO_TAG_PREFIX",
    "MOMO_TAG_KIND",
    "MOMO_TASK_ENV",
    "MOMO_RC_FORMAT",
];

/// A manifest with comments, unusual spacing, and a second table.
const MANIFEST: &str = "\
# The crate manifest.
[package]
name = \"proj\"   # the crate name
version = \"0.0.0\" # bumped by momo
edition = \"2024\"

[dependencies]
# a dependency
semver = \"1.0\"
";

/// [`MANIFEST`] with the version bumped to `0.1.0`.
const RELEASED: &str = "\
# The crate manifest.
[package]
name = \"proj\"   # the crate name
version = \"0.1.0\" # bumped by momo
edition = \"2024\"

[dependencies]
# a dependency
semver = \"1.0\"
";

/// A `momo` command rooted at `cwd`, with every `MOMO_*` variable cleared.
fn momo(cwd: &Path) -> Command {
    let mut cmd = Command::cargo_bin("momo").expect("the momo binary is built");
    cmd.current_dir(cwd);
    for name in MOMO_VARS {
        cmd.env_remove(name);
    }
    cmd
}

/// A project directory named `proj` under `dir`, so the Package name is stable.
fn project(dir: &TempDir) -> PathBuf {
    let path = dir.path().join("proj");
    fs::create_dir_all(&path).expect("create the project dir");
    path
}

/// Seed `MANIFEST` at `proj/Cargo.toml`.
fn seed_manifest(proj: &Path) -> PathBuf {
    let path = proj.join("Cargo.toml");
    fs::write(&path, MANIFEST).expect("seed the manifest");
    path
}

/// Read a file the test expects to exist.
fn read(path: &Path) -> String {
    fs::read_to_string(path).expect("read a file")
}

#[test]
fn release_rewrites_only_the_version_and_keeps_the_formatting() {
    let dir = TempDir::new().expect("temp dir");
    let proj = project(&dir);
    let manifest = seed_manifest(&proj);

    momo(&proj)
        .args(["add", "Add a shiny thing"])
        .assert()
        .success();
    momo(&proj)
        .arg("release")
        .assert()
        .success()
        .stdout(predicate::str::contains("released 0.1.0"));

    assert_eq!(read(&manifest), RELEASED);
}

#[test]
fn a_stale_lockfile_is_warned_about_and_left_alone() {
    let dir = TempDir::new().expect("temp dir");
    let proj = project(&dir);
    seed_manifest(&proj);
    let lockfile = proj.join("Cargo.lock");
    let locked = "# This file is automatically @generated by Cargo.\n";
    fs::write(&lockfile, locked).expect("seed the lockfile");

    momo(&proj)
        .args(["add", "Add a shiny thing"])
        .assert()
        .success();
    momo(&proj)
        .arg("release")
        .assert()
        .success()
        .stderr(predicate::str::contains("Cargo.lock"))
        .stderr(predicate::str::contains("may be stale"));

    assert_eq!(read(&lockfile), locked, "the lockfile was rewritten");
}

#[test]
fn a_release_without_a_manifest_still_succeeds() {
    let dir = TempDir::new().expect("temp dir");
    let proj = project(&dir);

    momo(&proj)
        .args(["add", "Add a shiny thing"])
        .assert()
        .success();
    momo(&proj)
        .arg("release")
        .assert()
        .success()
        .stderr(predicate::str::contains("stale").not());
}

#[test]
fn a_dry_run_release_leaves_the_manifest_alone() {
    let dir = TempDir::new().expect("temp dir");
    let proj = project(&dir);
    let manifest = seed_manifest(&proj);

    momo(&proj)
        .args(["add", "Add a shiny thing"])
        .assert()
        .success();
    momo(&proj)
        .args(["release", "--dry-run"])
        .assert()
        .success();

    assert_eq!(read(&manifest), MANIFEST);
    assert!(!proj.join(".momo/version").exists());
}

#[test]
fn status_never_writes_a_manifest() {
    let dir = TempDir::new().expect("temp dir");
    let proj = project(&dir);
    let manifest = seed_manifest(&proj);

    momo(&proj)
        .args(["add", "Add a shiny thing"])
        .assert()
        .success();
    momo(&proj)
        .arg("status")
        .assert()
        .success()
        .stdout(predicate::str::contains("→ next: 0.1.0"));

    assert_eq!(read(&manifest), MANIFEST);
}

#[test]
fn a_candidate_syncs_the_manifest_too() {
    let dir = TempDir::new().expect("temp dir");
    let proj = project(&dir);
    let manifest = seed_manifest(&proj);

    momo(&proj)
        .args(["add", "Add a shiny thing"])
        .assert()
        .success();
    momo(&proj).arg("candidate").assert().success();

    let updated = read(&manifest);
    assert!(updated.contains("version = \"0.1.0-rc.1\""), "{updated}");
}

#[test]
fn a_configured_manifest_override_is_synced() {
    let dir = TempDir::new().expect("temp dir");
    let proj = project(&dir);
    let conventional = seed_manifest(&proj);
    let override_path = proj.join("alt.toml");
    fs::write(&override_path, MANIFEST).expect("seed the override");
    fs::write(
        proj.join("momo.toml"),
        "[packages.proj]\nmanifest = \"alt.toml\"\n",
    )
    .expect("seed the config");

    momo(&proj)
        .args(["add", "Add a shiny thing"])
        .assert()
        .success();
    momo(&proj).arg("release").assert().success();

    assert_eq!(read(&override_path), RELEASED);
    assert_eq!(
        read(&conventional),
        MANIFEST,
        "discovery ignored the override"
    );
}
