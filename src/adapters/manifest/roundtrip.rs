//! Filesystem round-trips for the Cargo manifest adapter: a write changes only
//! the version scalar, and a lockfile is reported rather than rewritten.

use std::fs;
use std::path::Path;

use crate::adapters::manifest::CargoManifest;
use crate::domain::manifest::{ManifestEdits, ManifestSync, SkipReason};
use semver::Version;
use tempfile::TempDir;

/// A manifest with comments, unusual spacing, and a second table.
const MANIFEST: &str = "\
# The crate manifest.
[package]
name = \"momo\"   # the name
version = \"0.1.0\" # bumped by momo
edition = \"2024\"

[dependencies]
# a dependency
semver = \"1.0\"
";

/// [`MANIFEST`] with the version bumped to `0.2.0`.
const UPDATED: &str = "\
# The crate manifest.
[package]
name = \"momo\"   # the name
version = \"0.2.0\" # bumped by momo
edition = \"2024\"

[dependencies]
# a dependency
semver = \"1.0\"
";

/// The Cargo-generated lockfile header, standing in for a real one.
const LOCKFILE: &str = "# This file is automatically @generated by Cargo.\n";

fn version(text: &str) -> Version {
    text.parse().expect("a valid version")
}

/// The edits that sync only a version, leaving every range alone.
fn edits(text: &str) -> ManifestEdits {
    ManifestEdits::version(version(text))
}

#[test]
fn writing_a_manifest_rewrites_only_the_version_scalar() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, MANIFEST).expect("seed the manifest");

    let plan = CargoManifest
        .write(&path, &edits("0.2.0"))
        .expect("write the manifest");

    assert_eq!(plan.writes.len(), 1, "{plan:?}");
    assert_eq!(plan.writes[0].path, path);
    assert!(plan.lockfiles.is_empty(), "{plan:?}");
    assert!(plan.skipped.is_empty(), "{plan:?}");
    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        UPDATED
    );
}

#[test]
fn a_lockfile_beside_the_manifest_is_reported_and_left_alone() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    let lockfile = dir.path().join("Cargo.lock");
    fs::write(&path, MANIFEST).expect("seed the manifest");
    fs::write(&lockfile, LOCKFILE).expect("seed the lockfile");

    let plan = CargoManifest
        .write(&path, &edits("0.2.0"))
        .expect("write the manifest");

    assert_eq!(plan.lockfiles, vec![lockfile.clone()]);
    assert_eq!(
        fs::read_to_string(&lockfile).expect("read the lockfile"),
        LOCKFILE,
        "the lockfile was rewritten"
    );
}

#[test]
fn an_already_current_version_writes_nothing() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, MANIFEST).expect("seed the manifest");

    let plan = CargoManifest
        .write(&path, &edits("0.1.0"))
        .expect("write the manifest");

    assert!(plan.writes.is_empty(), "{plan:?}");
    assert_eq!(
        plan.skipped,
        vec![(path.clone(), SkipReason::AlreadyCurrent)],
        "{plan:?}"
    );
    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        MANIFEST
    );
}

#[test]
fn a_manifest_without_a_version_is_reported_as_skipped() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, "[package]\nname = \"momo\"\n").expect("seed the manifest");

    let plan = CargoManifest
        .write(&path, &edits("0.2.0"))
        .expect("write the manifest");

    assert!(plan.writes.is_empty(), "{plan:?}");
    assert_eq!(
        plan.skipped,
        vec![(path.clone(), SkipReason::NoVersion)],
        "{plan:?}"
    );
}

#[test]
fn writing_a_crlf_manifest_preserves_its_line_endings() {
    /// A CRLF manifest with no trailing newline.
    const CRLF: &str =
        "# The crate manifest.\r\n[package]\r\nname = \"momo\"\r\nversion = \"0.1.0\"";

    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, CRLF).expect("seed the manifest");

    CargoManifest
        .write(&path, &edits("0.2.0"))
        .expect("write the manifest");

    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        "# The crate manifest.\r\n[package]\r\nname = \"momo\"\r\nversion = \"0.2.0\""
    );
}

#[test]
fn rendering_a_manifest_leaves_the_file_untouched() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, MANIFEST).expect("seed the manifest");

    let plan = CargoManifest
        .render(&path, &edits("0.2.0"))
        .expect("render the manifest");

    assert_eq!(plan.writes.len(), 1, "{plan:?}");
    assert_eq!(plan.writes[0].path, path);
    assert_eq!(plan.writes[0].text, UPDATED);
    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        MANIFEST,
        "render rewrote the manifest"
    );
}

#[test]
fn writing_an_inherited_version_rewrites_the_workspace_root() {
    let dir = TempDir::new().expect("temp dir");
    let root = dir.path().join("Cargo.toml");
    let member_dir = dir.path().join("crates/a");
    fs::create_dir_all(&member_dir).expect("create the member dir");
    let member = member_dir.join("Cargo.toml");
    let root_text =
        "[workspace]\nmembers = [\"crates/a\"]\n\n[workspace.package]\nversion = \"0.1.0\"\n";
    let member_text = "[package]\nname = \"a\"\nversion.workspace = true\n";
    fs::write(&root, root_text).expect("seed the workspace root");
    fs::write(&member, member_text).expect("seed the member manifest");

    let plan = CargoManifest
        .write(&member, &edits("0.2.0"))
        .expect("write the manifest");

    assert_eq!(plan.writes.len(), 1, "{plan:?}");
    assert_eq!(plan.writes[0].path, root, "the write targeted the member");
    assert_eq!(
        fs::read_to_string(&root).expect("read the workspace root"),
        "[workspace]\nmembers = [\"crates/a\"]\n\n[workspace.package]\nversion = \"0.2.0\"\n"
    );
    assert_eq!(
        fs::read_to_string(&member).expect("read the member manifest"),
        member_text,
        "the member's own manifest was rewritten"
    );
}

#[test]
fn locate_finds_the_conventional_manifest() {
    let dir = TempDir::new().expect("temp dir");
    assert_eq!(CargoManifest.locate(dir.path(), None), None);

    fs::write(dir.path().join("Cargo.toml"), MANIFEST).expect("seed the manifest");
    assert_eq!(
        CargoManifest.locate(dir.path(), None),
        Some(dir.path().join("Cargo.toml"))
    );
}

#[test]
fn locate_prefers_the_configured_override() {
    let dir = TempDir::new().expect("temp dir");
    fs::write(dir.path().join("Cargo.toml"), MANIFEST).expect("seed the conventional manifest");
    fs::write(dir.path().join("alt.toml"), MANIFEST).expect("seed the override");

    assert_eq!(
        CargoManifest.locate(dir.path(), Some(Path::new("alt.toml"))),
        Some(dir.path().join("alt.toml"))
    );
}

#[test]
fn locate_skips_an_override_that_does_not_exist() {
    let dir = TempDir::new().expect("temp dir");
    fs::write(dir.path().join("Cargo.toml"), MANIFEST).expect("seed the manifest");

    assert_eq!(
        CargoManifest.locate(dir.path(), Some(Path::new("nope.toml"))),
        None
    );
}
