//! Filesystem round-trips for the Cargo manifest adapter: a write changes only
//! the version scalar, and a lockfile is reported rather than rewritten.

use std::fs;
use std::path::Path;

use crate::adapters::manifest::CargoManifest;
use crate::domain::manifest::ManifestSync;
use semver::Version;
use tempfile::TempDir;

/// A manifest with comments, unusual spacing, and a second table.
const MANIFEST: &str = "\
# The crate manifest.
[package]
name = \"momo\"   # the name
version = \"0.1.0\" # bumped by momo
edition = \"2024\"

[dependencies]
# a dependency
semver = \"1.0\"
";

/// [`MANIFEST`] with the version bumped to `0.2.0`.
const UPDATED: &str = "\
# The crate manifest.
[package]
name = \"momo\"   # the name
version = \"0.2.0\" # bumped by momo
edition = \"2024\"

[dependencies]
# a dependency
semver = \"1.0\"
";

/// The Cargo-generated lockfile header, standing in for a real one.
const LOCKFILE: &str = "# This file is automatically @generated by Cargo.\n";

fn version(text: &str) -> Version {
    text.parse().expect("a valid version")
}

#[test]
fn writing_a_manifest_rewrites_only_the_version_scalar() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, MANIFEST).expect("seed the manifest");

    let update = CargoManifest
        .write(&path, &version("0.2.0"))
        .expect("write the manifest")
        .expect("a manifest to sync");

    assert_eq!(update.manifest, path);
    assert_eq!(update.stale_lockfile, None);
    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        UPDATED
    );
}

#[test]
fn a_lockfile_beside_the_manifest_is_reported_and_left_alone() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    let lockfile = dir.path().join("Cargo.lock");
    fs::write(&path, MANIFEST).expect("seed the manifest");
    fs::write(&lockfile, LOCKFILE).expect("seed the lockfile");

    let update = CargoManifest
        .write(&path, &version("0.2.0"))
        .expect("write the manifest")
        .expect("a manifest to sync");

    assert_eq!(update.stale_lockfile.as_deref(), Some(lockfile.as_path()));
    assert_eq!(
        fs::read_to_string(&lockfile).expect("read the lockfile"),
        LOCKFILE,
        "the lockfile was rewritten"
    );
}

#[test]
fn an_already_current_version_writes_nothing() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, MANIFEST).expect("seed the manifest");

    let update = CargoManifest
        .write(&path, &version("0.1.0"))
        .expect("write the manifest");

    assert_eq!(update, None);
    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        MANIFEST
    );
}

#[test]
fn writing_a_crlf_manifest_preserves_its_line_endings() {
    /// A CRLF manifest with no trailing newline.
    const CRLF: &str =
        "# The crate manifest.\r\n[package]\r\nname = \"momo\"\r\nversion = \"0.1.0\"";

    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, CRLF).expect("seed the manifest");

    CargoManifest
        .write(&path, &version("0.2.0"))
        .expect("write the manifest")
        .expect("a manifest to sync");

    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        "# The crate manifest.\r\n[package]\r\nname = \"momo\"\r\nversion = \"0.2.0\""
    );
}

#[test]
fn rendering_a_manifest_leaves_the_file_untouched() {
    let dir = TempDir::new().expect("temp dir");
    let path = dir.path().join("Cargo.toml");
    fs::write(&path, MANIFEST).expect("seed the manifest");

    let (rendered, update) = CargoManifest
        .render(&path, &version("0.2.0"))
        .expect("render the manifest")
        .expect("a manifest to sync");

    assert_eq!(rendered, UPDATED);
    assert_eq!(update.manifest, path);
    assert_eq!(
        fs::read_to_string(&path).expect("read the manifest"),
        MANIFEST,
        "render rewrote the manifest"
    );
}

#[test]
fn locate_finds_the_conventional_manifest() {
    let dir = TempDir::new().expect("temp dir");
    assert_eq!(CargoManifest.locate(dir.path(), None), None);

    fs::write(dir.path().join("Cargo.toml"), MANIFEST).expect("seed the manifest");
    assert_eq!(
        CargoManifest.locate(dir.path(), None),
        Some(dir.path().join("Cargo.toml"))
    );
}

#[test]
fn locate_prefers_the_configured_override() {
    let dir = TempDir::new().expect("temp dir");
    fs::write(dir.path().join("Cargo.toml"), MANIFEST).expect("seed the conventional manifest");
    fs::write(dir.path().join("alt.toml"), MANIFEST).expect("seed the override");

    assert_eq!(
        CargoManifest.locate(dir.path(), Some(Path::new("alt.toml"))),
        Some(dir.path().join("alt.toml"))
    );
}

#[test]
fn locate_skips_an_override_that_does_not_exist() {
    let dir = TempDir::new().expect("temp dir");
    fs::write(dir.path().join("Cargo.toml"), MANIFEST).expect("seed the manifest");

    assert_eq!(
        CargoManifest.locate(dir.path(), Some(Path::new("nope.toml"))),
        None
    );
}
