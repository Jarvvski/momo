#[test]
fn has_unreleased_reports_a_non_empty_unreleased_section() {
    let with_entries = parse("# Changelog\n\n## [Unreleased]\n\n### Added\n\n- a thing\n");
    assert!(with_entries.has_unreleased());

    let empty_section = parse("# Changelog\n\n## [Unreleased]\n");
    assert!(!empty_section.has_unreleased());

    let released_only = parse("# Changelog\n\n## [1.0.0] - 2026-01-01\n");
    assert!(!released_only.has_unreleased());
}

#[test]
fn has_unreleased_counts_content_momo_cannot_parse() {
    // A `### Changed` body is Unreleased content even though momo models
    // only its three Kinds; a fragments release must not discard it.
    let text = "# Changelog\n\n## [Unreleased]\n\n### Changed\n\n- Reworked the parser\n";
    let changelog = parse(text);
    assert!(changelog.has_unreleased());
    assert!(changelog.unreleased().is_empty());
}

