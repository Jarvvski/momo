#[test]
fn a_release_sits_above_the_sections_already_there() {
    let text = "\
# Changelog

## [Unreleased]

### Added

- new thing

## [1.0.0] - 2026-01-01

### Added

- old thing
";
    let mut changelog = parse(text);
    let changes = changelog.unreleased();
    changelog.release(
        &Version::new(1, 1, 0),
        date(2026, 10, 13),
        &changes,
        no_links(),
    );

    let rendered = changelog.render();
    let new = rendered
        .find("## [1.1.0] - 2026-10-13")
        .expect("new heading");
    let old = rendered
        .find("## [1.0.0] - 2026-01-01")
        .expect("old heading");
    assert!(new < old, "{rendered}");
    assert!(!rendered.contains("## [Unreleased]"), "{rendered}");
    assert_eq!(
        changelog.released_versions(),
        vec![Version::new(1, 1, 0), Version::new(1, 0, 0)]
    );
}

