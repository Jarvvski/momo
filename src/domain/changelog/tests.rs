#[test]
fn sections_render_highest_kind_first() {
    let mut changelog = Changelog::empty();
    changelog.record(change(Kind::Fix, "a fix"));
    changelog.record(change(Kind::Add, "an add"));
    changelog.record(change(Kind::Break, "a break"));

    let rendered = changelog.render();
    let breaking = rendered.find("### Breaking").expect("breaking section");
    let added = rendered.find("### Added").expect("added section");
    let fixed = rendered.find("### Fixed").expect("fixed section");
    assert!(breaking < added && added < fixed, "{rendered}");
}

