#[test]
fn recording_preserves_released_sections_and_inserts_unreleased_first() {
    let text = "\
# Changelog

## [1.0.0] - 2026-01-01

### Added

- released thing
";
    let mut changelog = parse(text);
    assert!(changelog.unreleased().is_empty());
    changelog.record(change(Kind::Add, "new thing"));

    let rendered = changelog.render();
    let unreleased = rendered
        .find("## [Unreleased]")
        .expect("unreleased heading");
    let release = rendered
        .find("## [1.0.0] - 2026-01-01")
        .expect("release heading");
    assert!(unreleased < release, "{rendered}");
    assert!(rendered.contains("- new thing"), "{rendered}");
    assert!(rendered.contains("- released thing"), "{rendered}");
}

