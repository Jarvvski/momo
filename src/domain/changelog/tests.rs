#[test]
fn an_unrecognised_heading_and_its_bullets_survive_a_release() {
    let text = "\
# Changelog

## [Unreleased]

### Changed

- Reworked the parser

### Fixed

- a fix

## [1.0.0] - 2026-01-01

### Added

- old
";
    let mut changelog = parse(text);
    // `### Changed` is not one of momo's three Kinds, so it is preserved but
    // not interpreted; only the `### Fixed` bullet drives the bump.
    assert_eq!(changelog.unreleased(), &[change(Kind::Fix, "a fix")]);

    let changes = changelog.unreleased();
    changelog.release(
        &Version::new(1, 1, 0),
        date(2026, 10, 13),
        &changes,
        no_links(),
    );

    let rendered = changelog.render();
    assert!(rendered.contains("## [1.1.0] - 2026-10-13"), "{rendered}");
    assert!(
        rendered.contains("### Changed\n\n- Reworked the parser"),
        "the `### Changed` section was dropped:\n{rendered}"
    );
    assert!(rendered.contains("### Fixed\n\n- a fix"), "{rendered}");
    assert!(rendered.contains("## [1.0.0] - 2026-01-01"), "{rendered}");
}

