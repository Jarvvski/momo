#[test]
fn a_crlf_changelog_keeps_its_line_endings() {
    let text = "# Changelog\r\n\r\n## [Unreleased]\r\n\r\n### Added\r\n\r\n- a thing\r\n";
    let mut changelog = parse(text);
    assert_eq!(
        changelog.render(),
        text,
        "a CRLF document must round-trip unchanged"
    );

    changelog.record(change(Kind::Fix, "a fix"));
    let rendered = changelog.render();
    for (index, byte) in rendered.bytes().enumerate() {
        if byte == b'\n' {
            assert_eq!(
                rendered.as_bytes()[index - 1],
                b'\r',
                "a bare LF in a CRLF changelog:\n{rendered:?}"
            );
        }
    }
    assert!(rendered.contains("- a fix\r\n"), "{rendered:?}");
}

