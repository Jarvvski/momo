#[test]
fn is_owned_link_matches_only_momo_reference_links() {
    assert!(is_owned_link(
        "[Unreleased]: https://example.com/compare/v1.0.0...HEAD"
    ));
    assert!(is_owned_link("[unreleased]: https://example.com"));
    assert!(is_owned_link("[1.2.3]: https://example.com/tags/v1.2.3"));
    assert!(is_owned_link("[1.2.3-rc.1]: https://example.com"));
    assert!(!is_owned_link(
        "[Keep a Changelog]: https://keepachangelog.com/en/1.0.0/"
    ));
    assert!(!is_owned_link(
        "[Semantic Versioning]: https://semver.org/spec/v2.0.0.html"
    ));
    assert!(!is_owned_link("not a link at all"));
}

