    #[test]
    fn last_release_ranks_by_version_not_by_document_order() {
        // A hand-written document may list its releases oldest-first; the
        // accessor must take the highest stable Version, not the first heading.
        let ascending = "\
# Changelog

## [0.1.0] - 2026-01-01

### Added

- old thing

## [0.2.0] - 2026-02-01

### Added

- newer thing
";
        assert_eq!(parse(ascending).last_release(), Some(Version::new(0, 2, 0)));

        // A lexicographic or positional pick would return `0.1.0`; semver
        // precedence must prefer `0.10.0`.
        let mixed = "\
# Changelog

## [0.10.0] - 2026-03-01

## [0.9.0] - 2026-02-01
";
        assert_eq!(parse(mixed).last_release(), Some(Version::new(0, 10, 0)));
    }

