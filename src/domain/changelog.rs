/// The title and intro written above the first `##` heading of a new changelog.
const INTRO: &str = "\
# Changelog

All notable changes to this package are documented here, generated by
[momo](https://github.com/Jarvvski/momo).";

/// The heading momo writes for a new Unreleased section.
const UNRELEASED_HEADING: &str = "## [Unreleased]";

/// The error produced when a changelog cannot be edited without data loss.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ChangelogError {
    /// The document carries more than one Unreleased heading, so momo cannot
    /// tell which section to record into or promote.
    #[error(
        "line {line}: the changelog has more than one Unreleased section; \
         momo cannot tell which one to use"
    )]
    DuplicateUnreleased {
        /// The 1-based line of the second Unreleased heading.
        line: usize,
    },
    /// The Unreleased body holds bullets under a Keep-a-Changelog heading momo
    /// cannot read, so a mint would silently under-version them.
    #[error(
        "`### {heading}` has {entries} {noun} momo cannot version (line {line})",
        noun = plural(*entries)
    )]
    UnreadSection {
        /// The heading, e.g. `Changed`, without the `### ` prefix.
        heading: String,
        /// The 1-based line of the heading.
        line: usize,
        /// The number of `- ` bullets beneath it.
        entries: usize,
    },
}

/// "entry" for one, "entries" otherwise — the count in an error message.
fn plural(count: usize) -> &'static str {
    if count == 1 { "entry" } else { "entries" }
}

impl_coded! {
    ChangelogError {
        ChangelogError::DuplicateUnreleased { .. } => (
            "momo.changelog.duplicate-unreleased",
            fix = "remove the duplicate `## [Unreleased]` heading",
        ),
        ChangelogError::UnreadSection { .. } => (
            "momo.changelog.unversioned-section",
            fix = "move them under `### Breaking`/`### Added`/`### Fixed`, or — if they are not \
                   versioned changes — out of a Keep-a-Changelog heading momo reads",
        ),
    }
}

/// The line ending a changelog uses, reapplied to every line momo writes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Ending {
    /// Unix line endings.
    Lf,
    /// Windows line endings.
    Crlf,
}

impl Ending {
    /// The terminator this ending writes.
    fn as_str(self) -> &'static str {
        match self {
            Ending::Lf => "\n",
            Ending::Crlf => "\r\n",
        }
    }
}

/// One `##` section: its heading and the body lines beneath it.
///
/// The body is stored verbatim, apart from trailing blank lines, which are the
/// separator to the next section and are re-emitted on render.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Section {
    /// The `## …` heading line, without its terminator.
    heading: String,
    /// The lines beneath the heading, without terminators.
    body: Vec<String>,
    /// The 1-based document line of the heading; `0` for a section momo builds
    /// rather than parses (it has no document line until it is rendered).
    line: usize,
}

/// A Keep-a-Changelog heading momo cannot read, and the Unreleased bullets
/// beneath it.
///
/// The heading names a Keep-a-Changelog classification ([`Kind::from_heading`]
/// does not read) that momo has no honest Bump for. Its bullets are Unreleased
/// Changes momo is failing to version, so a mint refuses them rather than
/// under-versioning the Release; `status` reports them instead of erroring.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnreadSection {
    /// The heading, e.g. `Changed`, without the `### ` prefix.
    pub heading: String,
    /// The 1-based document line of the heading.
    pub line: usize,
    /// The number of `- ` bullets beneath it.
    pub entries: usize,
}

/// A preserved `CHANGELOG.md`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Changelog {
    /// The lines before the first `##` section, without terminators.
    preamble: Vec<String>,
    /// Every `##` section, in document order.
    sections: Vec<Section>,
    /// The trailing reference-link definitions, without the separator blank.
    footer: Vec<String>,
    /// The line ending the document uses.
    ending: Ending,
}

impl Changelog {
    /// A new changelog holding only the standard intro.
    ///
    /// It has no Unreleased section yet; recording a Change creates one.
    pub fn empty() -> Self {
        Self {
            preamble: INTRO.lines().map(str::to_owned).collect(),
            sections: Vec::new(),
            footer: Vec::new(),
            ending: Ending::Lf,
        }
    }

    /// Parse `text` into a changelog.
    ///
    /// Fails when the document has more than one Unreleased section: momo cannot
    /// tell which one to record into or promote, and silently picking one would
    /// lose the other.
    pub fn parse(text: &str) -> Result<Self, ChangelogError> {
        let ending = detect_ending(text);
        let lines: Vec<&str> = text.lines().collect();
        let (content, footer) = split_footer(&lines);

        let mut preamble = Vec::new();
        let mut sections: Vec<Section> = Vec::new();
        let mut current: Option<Section> = None;
        let mut unreleased = false;

        for (index, line) in content.iter().enumerate() {
            if is_section(line) {
                if is_unreleased(line) {
                    if unreleased {
                        return Err(ChangelogError::DuplicateUnreleased { line: index + 1 });
                    }
                    unreleased = true;
                }
                if let Some(section) = current.take() {
                    sections.push(section);
                }
                current = Some(Section {
                    heading: (*line).to_owned(),
                    body: Vec::new(),
                    line: index + 1,
                });
            } else if let Some(section) = current.as_mut() {
                section.body.push((*line).to_owned());
            } else {
                preamble.push((*line).to_owned());
            }
        }
        if let Some(section) = current.take() {
            sections.push(section);
        }

        // The blank line separating the body from a section, or a footer, is
        // re-emitted on render, so it is not kept here. Without a section or a
        // footer the preamble is the whole document and is left untouched.
        if !sections.is_empty() || !footer.is_empty() {
            trim_trailing_blanks(&mut preamble);
        }
        for section in &mut sections {
            trim_trailing_blanks(&mut section.body);
        }

        Ok(Self {
            preamble,
            sections,
            footer: owned(footer),
            ending,
        })
    }

    /// Record one Change under Unreleased.
    ///
    /// The entry lands under the section's matching `### Kind` heading, or a new
    /// heading is inserted in Kind order. Every other line of the Unreleased
    /// body — foreign headings, comments, `*` bullets — is left where it is.
    pub fn record(&mut self, change: Change) {
        match self.unreleased_index() {
            Some(index) => append_change(&mut self.sections[index], change),
            None => {
                let mut section = Section {
                    heading: UNRELEASED_HEADING.to_owned(),
                    body: Vec::new(),
                    line: 0,
                };
                append_change(&mut section, change);
                self.sections.insert(0, section);
            }
        }
    }

    /// The Unreleased Changes momo understands.
    ///
    /// Only `- ` bullets under the three recognised `### Kind` headings are
    /// returned; everything else in the Unreleased body is preserved but not
    /// interpreted.
    pub fn unreleased(&self) -> Vec<Change> {
        self.unreleased_index()
            .map(|index| entries(&self.sections[index].body))
            .unwrap_or_default()
    }

    /// The Unreleased sections under a heading momo cannot read.
    ///
    /// The Unreleased body is the Bump source, so a bullet under `### Changed`
    /// or its Keep-a-Changelog siblings is an Unreleased Change momo is failing
    /// to version. Only the Unreleased section is inspected: a released
    /// section's `### Changed` is history, never parsed for entries, and must
    /// not fail a project adopting momo over an existing Keep-a-Changelog file.
    pub fn unread_sections(&self) -> Vec<UnreadSection> {
        self.unreleased_index()
            .map(|index| parse::unread_sections(&self.sections[index]))
            .unwrap_or_default()
    }

    /// Refuse the changelog when the Unreleased body holds entries momo cannot
    /// read.
    ///
    /// A mint would silently drop them from the Bump and under-version the
    /// Release. The first offending section is named, with its line and a
    /// one-line fix.
    pub fn reject_unread(&self) -> Result<(), ChangelogError> {
        match self.unread_sections().into_iter().next() {
            Some(section) => Err(ChangelogError::UnreadSection {
                heading: section.heading,
                line: section.line,
                entries: section.entries,
            }),
            None => Ok(()),
        }
    }

    /// Whether the document has a non-empty Unreleased section.
    ///
    /// "Non-empty" means the body holds a non-blank line of any kind, not just a
    /// recognised entry: a hand-written `### Changed` body is Unreleased content
    /// that a Release must not silently discard. A bare heading is not Unreleased
    /// — there is nothing to promote, and a fresh Changelog template carries one.
    pub fn has_unreleased(&self) -> bool {
        self.unreleased_index()
            .is_some_and(|index| has_content(&self.sections[index].body))
    }

    /// Consume the changelog, returning its Unreleased Changes.
    pub fn into_unreleased(self) -> Vec<Change> {
        self.unreleased()
    }

    /// Promote the Unreleased section into a Release.
    ///
    /// The whole Unreleased body moves verbatim into a section headed
    /// `## [version] - date`, placed above the existing releases, and the
    /// Unreleased section is consumed. The reference links are refreshed for
    /// `links`.
    ///
    /// `changes` is the fallback body when there is no Unreleased section to move
    /// (the fragment recording model); when one exists, its preserved body wins
    /// so nothing the parser cannot model is dropped.
    pub fn release(&mut self, version: &Version, date: Date, changes: &[Change], links: Links<'_>) {
        let body = self.take_unreleased_body(changes);
        self.sections
            .insert(0, release_section(version, date, body));
        self.refresh_footer(links);
    }

    /// Record a Release Candidate section for `version`.
    ///
    /// The section carries a copy of the Unreleased body and the Unreleased
    /// section is left in place, because a Candidate shares its changes with the
    /// eventual Release.
    pub fn candidate(
        &mut self,
        version: &Version,
        date: Date,
        changes: &[Change],
        links: Links<'_>,
    ) {
        let body = match self.unreleased_index() {
            Some(index) if has_content(&self.sections[index].body) => {
                self.sections[index].body.clone()
            }
            _ => body_from_changes(changes),
        };
        self.sections
            .insert(0, release_section(version, date, body));
        self.refresh_footer(links);
    }

    /// The Versions named by the released section headings, in document order.
    ///
    /// The Unreleased heading is not a release; hand-written headings that are
    /// not semver are skipped.
    pub fn released_versions(&self) -> Vec<Version> {
        self.sections
            .iter()
            .filter(|section| !is_unreleased(&section.heading))
            .filter_map(|section| heading_version(&section.heading))
            .collect()
    }

    /// The newest stable Release the released headings name, if any.
    ///
    /// "Newest" is by semver precedence, not by position: a hand-written document
    /// may list its releases in any order, and the highest stable Version wins.
    /// On a precedence tie the Version without build metadata wins, matching the
    /// tag ranking. A Release Candidate heading is skipped: the base for the next
    /// bump is the Release it was cut from, not the Candidate. Used as the
    /// fallback base when a Package's version source cannot report its last
    /// release.
    pub fn last_release(&self) -> Option<Version> {
        self.released_versions()
            .into_iter()
            .filter(|version| version.pre.is_empty())
            .max_by(cmp_version_rank)
    }

    /// The index of the Unreleased section, when the document has one.
    fn unreleased_index(&self) -> Option<usize> {
        self.sections
            .iter()
            .position(|section| is_unreleased(&section.heading))
    }

    /// Remove the Unreleased section, returning the body to promote.
    ///
    /// A bare heading has no body to move, so `fallback` — the Changes the run
    /// minted from — is used instead.
    fn take_unreleased_body(&mut self, fallback: &[Change]) -> Vec<String> {
        match self.unreleased_index() {
            Some(index) => {
                let body = self.sections.remove(index).body;
                if has_content(&body) {
                    body
                } else {
                    body_from_changes(fallback)
                }
            }
            None => body_from_changes(fallback),
        }
    }

    /// Regenerate momo's own reference links, preserving every other definition.
    ///
    /// The `[Unreleased]` link is emitted only while the document has an
    /// Unreleased section; a Release consumes that section, so its footer would
    /// otherwise carry a dangling link definition. Definitions momo does not
    /// own — the prose links a Keep-a-Changelog footer carries — are kept in
    /// place. Without a remote there is nothing to regenerate, so the footer is
    /// left exactly as it was.
    fn refresh_footer(&mut self, links: Links<'_>) {
        let Some(remote) = links.remote else {
            return;
        };
        let mut footer: Vec<String> = self
            .footer
            .iter()
            .filter(|line| !is_owned_link(line))
            .cloned()
            .collect();
        footer.extend(remote.footer(
            &self.released_versions(),
            links.prefix,
            self.has_unreleased(),
        ));
        self.footer = footer;
    }

    /// Render the changelog back to Markdown.
    pub fn render(&self) -> String {
        let mut lines = self.preamble.clone();
        for section in &self.sections {
            blank(&mut lines);
            lines.push(section.heading.clone());
            lines.extend(section.body.iter().cloned());
        }
        if !self.footer.is_empty() {
            blank(&mut lines);
            lines.extend(self.footer.iter().cloned());
        }

        let mut rendered = lines.join(self.ending.as_str());
        rendered.push_str(self.ending.as_str());
        rendered
    }
}

/// Where a Changelog's reference links point.
#[derive(Debug, Clone, Copy)]
pub struct Links<'a> {
    /// The tag prefix, e.g. `v` or `cargo-momo-v`.
    pub prefix: &'a str,
    /// The remote to link to; `None` omits the footer entirely.
    pub remote: Option<&'a Remote>,
}
