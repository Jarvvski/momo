//! The `CHANGELOG.md` document: recording a Change into it, and promoting the
//! Unreleased section into a Release.
//!
//! The changelog is **preserved**, not round-tripped through a parsed struct:
//! momo keeps the document's original lines and edits only the spans it owns —
//! the Unreleased body, its own reference-link footer lines, and the release
//! headings it inserts. Everything else passes through byte-for-byte: CRLF line
//! endings, `*` bullets, HTML comments, `### Changed` headings and user-authored
//! footer definitions all survive a `record` and a `release`. A document momo
//! cannot edit without touching foreign content is refused, naming the line.
//!
//! Pure text: reading and writing the file is the CLI's job.

